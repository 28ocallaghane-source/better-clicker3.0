-- Better Clicker 3.0 online backend setup
-- Run this entire file in Supabase Dashboard > SQL Editor.
-- Never put a service_role/secret key in the HTML file.

create extension if not exists pgcrypto;

create table if not exists public.profiles (
  id uuid primary key references auth.users(id) on delete cascade,
  username text not null check (username ~ '^[A-Za-z0-9_]{3,20}$'),
  created_at timestamptz not null default now()
);
create unique index if not exists profiles_username_ci_unique on public.profiles (lower(username));

create table if not exists public.game_saves (
  user_id uuid primary key references auth.users(id) on delete cascade,
  game_state jsonb not null default '{}'::jsonb,
  achievements_unlocked jsonb not null default '{}'::jsonb,
  last_active_at timestamptz not null default now(),
  updated_at timestamptz not null default now()
);

create table if not exists public.leaderboard_scores (
  user_id uuid primary key references auth.users(id) on delete cascade,
  total_coins numeric not null default 0,
  rebirths integer not null default 0,
  updated_at timestamptz not null default now()
);

create table if not exists public.global_chat (
  id bigint generated by default as identity primary key,
  user_id uuid not null references public.profiles(id) on delete cascade,
  content text not null check (char_length(content) between 1 and 240),
  created_at timestamptz not null default now()
);

create table if not exists public.private_messages (
  id bigint generated by default as identity primary key,
  sender_id uuid not null references public.profiles(id) on delete cascade,
  recipient_id uuid not null references public.profiles(id) on delete cascade,
  content text not null check (char_length(content) between 1 and 240),
  created_at timestamptz not null default now(),
  constraint private_messages_not_self check (sender_id <> recipient_id)
);
create index if not exists private_messages_pair_created_idx
  on public.private_messages (sender_id, recipient_id, created_at);
create index if not exists private_messages_recipient_created_idx
  on public.private_messages (recipient_id, created_at);

-- Public leaderboard exposes scores and usernames only, never full saves.
create or replace view public.leaderboard
with (security_invoker = false) as
select p.username, l.total_coins, l.rebirths, l.updated_at
from public.leaderboard_scores l
join public.profiles p on p.id = l.user_id;

-- Create profile automatically when Supabase Auth creates a user.
create or replace function public.handle_new_better_clicker_user()
returns trigger
language plpgsql
security definer
set search_path = ''
as $$
declare
  chosen_username text;
begin
  chosen_username := new.raw_user_meta_data ->> 'username';
  if chosen_username is null or chosen_username !~ '^[A-Za-z0-9_]{3,20}$' then
    chosen_username := 'Player_' || substr(replace(new.id::text, '-', ''), 1, 10);
  end if;
  insert into public.profiles (id, username)
  values (new.id, chosen_username);
  return new;
end;
$$;
drop trigger if exists on_auth_user_created_better_clicker on auth.users;
create trigger on_auth_user_created_better_clicker
after insert on auth.users
for each row execute procedure public.handle_new_better_clicker_user();

-- Keep the public leaderboard in sync with the save, server-side.
create or replace function public.sync_better_clicker_leaderboard()
returns trigger
language plpgsql
security definer
set search_path = ''
as $$
begin
  insert into public.leaderboard_scores (user_id, total_coins, rebirths, updated_at)
  values (
    new.user_id,
    greatest(coalesce((new.game_state ->> 'totalCoins')::numeric, 0), 0),
    greatest(coalesce((new.game_state ->> 'rebirths')::integer, 0), 0),
    now()
  )
  on conflict (user_id) do update set
    total_coins = excluded.total_coins,
    rebirths = excluded.rebirths,
    updated_at = now();
  return new;
end;
$$;
drop trigger if exists on_game_save_changed_better_clicker on public.game_saves;
create trigger on_game_save_changed_better_clicker
after insert or update of game_state on public.game_saves
for each row execute procedure public.sync_better_clicker_leaderboard();

alter table public.profiles enable row level security;
alter table public.game_saves enable row level security;
alter table public.leaderboard_scores enable row level security;
alter table public.global_chat enable row level security;
alter table public.private_messages enable row level security;

-- Remove old policies first so the script can be run again safely.
drop policy if exists "Profiles are visible for username lookup" on public.profiles;
drop policy if exists "Users can read own save" on public.game_saves;
drop policy if exists "Users can insert own save" on public.game_saves;
drop policy if exists "Users can update own save" on public.game_saves;
drop policy if exists "Leaderboard is readable" on public.leaderboard_scores;
drop policy if exists "Users can read own leaderboard row" on public.leaderboard_scores;
drop policy if exists "Global chat is readable by signed-in users" on public.global_chat;
drop policy if exists "Signed-in users can post as themselves" on public.global_chat;
drop policy if exists "Users can read messages they sent or received" on public.private_messages;
drop policy if exists "Users can send private messages as themselves" on public.private_messages;

-- Usernames are public, but emails and auth records are not.
create policy "Profiles are visible for username lookup"
  on public.profiles for select to anon, authenticated using (true);

create policy "Users can read own save" on public.game_saves
  for select to authenticated using ((select auth.uid()) = user_id);
create policy "Users can insert own save" on public.game_saves
  for insert to authenticated with check ((select auth.uid()) = user_id);
create policy "Users can update own save" on public.game_saves
  for update to authenticated using ((select auth.uid()) = user_id) with check ((select auth.uid()) = user_id);

-- Only the trusted trigger writes leaderboard_scores. Direct client access is denied.

create policy "Global chat is readable by signed-in users" on public.global_chat
  for select to authenticated using (true);
create policy "Signed-in users can post as themselves" on public.global_chat
  for insert to authenticated with check ((select auth.uid()) = user_id);

create policy "Users can read messages they sent or received" on public.private_messages
  for select to authenticated using ((select auth.uid()) = sender_id or (select auth.uid()) = recipient_id);
create policy "Users can send private messages as themselves" on public.private_messages
  for insert to authenticated with check ((select auth.uid()) = sender_id and sender_id <> recipient_id);

-- Least-privilege grants for exposed tables.
revoke all on public.profiles from anon, authenticated;
grant select (id, username, created_at) on public.profiles to anon, authenticated;
revoke all on public.game_saves from anon, authenticated;
grant select, insert, update on public.game_saves to authenticated;
revoke all on public.leaderboard_scores from anon, authenticated;
revoke all on public.leaderboard from anon, authenticated;
grant select on public.leaderboard to anon, authenticated;
revoke all on public.global_chat from anon, authenticated;
grant select, insert on public.global_chat to authenticated;
revoke all on public.private_messages from anon, authenticated;
grant select, insert on public.private_messages to authenticated;

-- Enable realtime updates for cross-device chat/leaderboard refresh.
do $$
begin
  if not exists (select 1 from pg_publication_tables where pubname = 'supabase_realtime' and schemaname = 'public' and tablename = 'global_chat') then
    alter publication supabase_realtime add table public.global_chat;
  end if;
  if not exists (select 1 from pg_publication_tables where pubname = 'supabase_realtime' and schemaname = 'public' and tablename = 'game_saves') then
    alter publication supabase_realtime add table public.game_saves;
  end if;
  if not exists (select 1 from pg_publication_tables where pubname = 'supabase_realtime' and schemaname = 'public' and tablename = 'private_messages') then
    alter publication supabase_realtime add table public.private_messages;
  end if;
end;
$$;
